//! Implicitly declared operations (sem.md 2.10, `lib/NATIVE.md` section 2).
//!
//! Every predefined operation is a real `DeclKind::Subprogram` entity, created
//! in the same region right after its type, with `implicit = true`, so
//! visibility, hiding, aliases, `use p."+"` and overload resolution need no
//! special cases.

use crate::ids::TypeId;

/// The native link of an implicit op is `rsim.implicit.<family>.<type mangled>`.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct ImplicitOp {
    pub family: Family,
    pub ty: TypeId,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Family {
    Eq,
    Neq,
    Lt,
    Le,
    Gt,
    Ge,
    Minimum,
    Maximum,
    ToString,
    Add,
    Sub,
    Mul,
    Div,
    Neg,
    Pos,
    Abs,
    Exp,
    Rem,
    Mod,
    And,
    Or,
    Nand,
    Nor,
    Xor,
    Xnor,
    Not,
    /// Matching relational operators `?=` etc. and the condition operator `??`.
    MEq,
    MNeq,
    MLt,
    MLe,
    MGt,
    MGe,
    Cond,
    Cat,
    Sll,
    Srl,
    Sla,
    Sra,
    Rol,
    Ror,
    ToOString,
    ToHString,
    Deallocate,
    FileOpen,
    FileClose,
    Read,
    Write,
    Endfile,
    Flush,
    FileState,
    FileMode,
    FilePosition,
    FileSize,
    FileSeek,
    FileTruncate,
    FileRewind,
    RisingEdge,
    FallingEdge,
}

impl Family {
    /// The family part of the native symbol.
    pub fn as_str(self) -> &'static str {
        use Family::*;
        match self {
            Eq => "eq",
            Neq => "neq",
            Lt => "lt",
            Le => "le",
            Gt => "gt",
            Ge => "ge",
            Minimum => "minimum",
            Maximum => "maximum",
            ToString => "to_string",
            Add => "add",
            Sub => "sub",
            Mul => "mul",
            Div => "div",
            Neg => "neg",
            Pos => "pos",
            Abs => "abs",
            Exp => "exp",
            Rem => "rem",
            Mod => "mod",
            And => "and",
            Or => "or",
            Nand => "nand",
            Nor => "nor",
            Xor => "xor",
            Xnor => "xnor",
            Not => "not",
            MEq => "meq",
            MNeq => "mneq",
            MLt => "mlt",
            MLe => "mle",
            MGt => "mgt",
            MGe => "mge",
            Cond => "cond",
            Cat => "cat",
            Sll => "sll",
            Srl => "srl",
            Sla => "sla",
            Sra => "sra",
            Rol => "rol",
            Ror => "ror",
            ToOString => "to_ostring",
            ToHString => "to_hstring",
            Deallocate => "deallocate",
            FileOpen => "file_open",
            FileClose => "file_close",
            Read => "read",
            Write => "write",
            Endfile => "endfile",
            Flush => "flush",
            FileState => "file_state",
            FileMode => "file_mode",
            FilePosition => "file_position",
            FileSize => "file_size",
            FileSeek => "file_seek",
            FileTruncate => "file_truncate",
            FileRewind => "file_rewind",
            RisingEdge => "rising_edge",
            FallingEdge => "falling_edge",
        }
    }
}
