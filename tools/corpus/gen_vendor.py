#!/usr/bin/env python3
"""Generate tools/corpus/unisim-2008.toml from a locally installed vendor primitive library tree.

    YAVS_VENDOR_UNISIM=<dir holding unisims/ and unimacro/> gen_vendor.py

The tree is read in place and never copied or committed; the manifest holds only relative file names, in
the order of the vendor's own analyze-order lists. run.py skips the manifest when the variable is unset.
"""
import os, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import simconf  # noqa: E402

root = os.environ.get("YAVS_VENDOR_UNISIM")
if not root or not (Path(root) / "unisims").is_dir():
    sys.exit("set YAVS_VENDOR_UNISIM to the directory that holds unisims/ and unimacro/")
root = Path(root)


def order(d):
    return [(d / l).as_posix() for l in (root / d / "vhdl_analyze_order").read_text().split() if l.strip()]


files = [("unisim", "unisims/unisim_VPKG.vhd"), ("unisim", "unisims/unisim_retarget_VCOMP.vhd")]
files += [("unisim", p) for p in order(Path("unisims/primitive"))] + [("unisim", p) for p in order(Path("unisims/retarget"))]
files += [("unimacro", p) for p in order(Path("unimacro"))]
out = ['# Generated by tools/corpus/gen_vendor.py; do not edit by hand.',
       '# Vendor primitive libraries, read in place from $YAVS_VENDOR_UNISIM (never committed); run.py skips this manifest when unset.',
       'name = "unisim-2008"', 'std = "2008"', 'exclude = []', '']
out += ["file = ["] + [f'  {{ lib = "{l}", source = "unisim", path = "{p}", std = "2008" }},' for l, p in files] + ["]", "",
      "[flags]", "sim1 = []", "yavs = []", "", "[[source]]", 'id = "unisim"', 'env = "YAVS_VENDOR_UNISIM"']
(Path(__file__).parent / "unisim-2008.toml").write_text("\n".join(out) + "\n")
print(len(files), "files")
