#!/usr/bin/env bash
# Regenerate tools/corpus/RESULTS.md: run every corpus manifest through yavs (no expected-list
# comparison, nothing is blessed) and group the failures by first diagnostic.
#   tools/corpus/report.sh [YAVS_BINARY]     (default: target/release/yavs, built here)
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
repo=$(cd "$here/../.." && pwd)
bin=${1:-}
if [ -z "$bin" ]; then
    (cd "$repo" && cargo build -q --release -p yavs)
    bin=${CARGO_TARGET_DIR:-$repo/target}/release/yavs
fi
work=$(mktemp -d "${TMPDIR:-$HOME/.cache}/yavs-report.XXXXXX")
mkdir -p "$work/bin" && ln -s "$(readlink -f "$bin")" "$work/bin/yavs"
export PATH=$work/bin:$PATH
for m in "$here"/*.toml; do basename "$m" .toml; done |
    xargs -P 4 -I{} sh -c "python3 '$here/run.py' {} --tool yavs --expected none --keep-going --out '$work/out-{}' --log '$work/{}.log' > '$work/{}.out' 2>&1 || true"
python3 -I - "$work" "$("$bin" --version)" <<'PY' > "$here/RESULTS.md"
import re, sys, collections
from pathlib import Path
work, ver = Path(sys.argv[1]), sys.argv[2]
print(f"# Analysis corpus results for yavs\n\nGenerated by `tools/corpus/report.sh` with `{ver}`. Expected lists are not consulted.\n")
print("| corpus | pass | fail | total |\n|---|---|---|---|")
allg = collections.defaultdict(list)
for out in sorted(work.glob("*.out")):
    name = out.stem
    m = re.search(r"(\d+) PASS, (\d+) FAIL of (\d+)", out.read_text())
    print(f"| {name} | {m[1]} | {m[2]} | {m[3]} |" if m else f"| {name} | ? | ? | ? (run did not finish) |")
    log = work / f"{name}.log"
    if not log.exists():
        continue
    for blk in re.split(r"^=== ", log.read_text(errors="replace"), flags=re.M)[1:]:
        head, _, body = blk.partition("\n")
        f = head.split(" (exit")[0]
        d = re.search(r"^(error|warning)(\[(\w+)\])?: (.*)$", body, re.M)
        if not d:
            key = "(no diagnostic) " + (body.strip().splitlines() or ["empty output"])[0][:80]
        else:
            key = f"{d[3] or '-'}: " + re.sub(r"`[^`]*`", "`_`", d[4])
        loc = re.search(r"^\s*--> (\S+)", body[d.end():] if d else body, re.M)
        allg[key].append((f, re.sub(r"^.*/(yavs|rsim)-corpus/", "", re.sub(r"^.*?/lib/", "lib/", loc[1]) if "-corpus/" not in loc[1] else loc[1]) if loc else "-", name))
CASCADE = ("E1002:", "E1004:", "L0001:")  # a unit or library missing because an earlier file failed
for title, keep in (("all", lambda k: True), ("without cascades (missing unit or library: E1002, E1004, L0001)", lambda k: not k.startswith(CASCADE))):
    print(f"\n## Failures grouped by first diagnostic (top 30, {title})\n")
    print("| count | first diagnostic | example |\n|---|---|---|")
    for key, v in sorted(((k, v) for k, v in allg.items() if keep(k)), key=lambda kv: -len(kv[1]))[:30]:
        print(f"| {len(v)} | `{key}` | {v[0][2]}: {v[0][1]} |")
print("\n## Per corpus (top 10 groups each)\n")
per = collections.defaultdict(collections.Counter)
ex = {}
for key, v in allg.items():
    for f, loc, c in v:
        per[c][key] += 1
        ex.setdefault((c, key), loc)
for c in sorted(per):
    print(f"### {c}\n")
    for key, n in per[c].most_common(10):
        print(f"- {n} x `{key}` (e.g. {ex[(c, key)]})")
    print()
PY
rm -r "$work"
