#!/usr/bin/env python3
"""Turn difftest --json results into tests/corpus/RESULTS.md. Usage: report.py OUT.md RUN=file.json ...
(the first RUN is the base run; its failures are grouped). Stdlib only."""
import collections, json, re, sys

OWNER_BY_CODE = [(r"^E0[0-9]{3}$", "yavs-syntax / yavs-lib"), (r"^E1[0-9]{3}$", "yavs-sem")]
# first matching message pattern wins; unmatched elaboration errors go to yavs-elab
OWNER_BY_MSG = [
    (r"native|builtin|instruction|opcode", "yavs-interp"),
    (r"running processes|lower", "yavs-lower / yavs-interp (wiring in yavs-elab)"),
    (r"guarded|elaborat", "yavs-elab"),
]


def first_error(r):
    if r["ok"]:
        return None
    raw = r.get("raw") or r["msg"]
    m = re.search(r"^error\[(\w+)\]: (.*)$", raw, re.M)
    loc = re.search(r"^\s*--> (\S+)", raw, re.M)
    at = loc.group(1).split("/")[-1] if loc else ""
    if m:
        code, msg = m.groups()
        return r.get("stage") or "run", code, msg, at
    if r["msg"].startswith("timeout"):
        return "run", "-", "timeout", ""
    if "differs" in r["msg"] or "expected" in r["msg"]:
        line = next((l for l in r["msg"].splitlines() if l.startswith(("+", "-")) and not l.startswith(("+++", "---"))), "")
        return "output", "-", "output mismatch", line[:90]
    return r.get("stage") or "run", "-", r["msg"].splitlines()[0][:100], ""


def owner(stage, code, msg):
    if stage == "output":
        return "yavs-kernel / yavs-std / yavs-interp (triage per case)"
    if stage == "analysis":
        for p, o in OWNER_BY_CODE:
            if re.match(p, code):
                return o
    for p, o in OWNER_BY_MSG:
        if re.search(p, msg, re.I):
            return o
    return {"elab": "yavs-elab", "analysis": "yavs-sem"}.get(stage, "yavs (CLI)")


def load(path):
    return [json.loads(l) for l in open(path)]


def main():
    out, runs = sys.argv[1], [a.split("=", 1) for a in sys.argv[2:]]
    data = {n: load(f) for n, f in runs}
    base = next(iter(data))
    groups = sorted({r["name"].split("/")[0] for r in data[base]})
    L = ["# Differential corpus results (yavs vs the reference simulator `.expected`)", "",
         "Generated by `tools/difftest/report.sh`; do not edit by hand. Strict mode (no ignored fields).", "",
         "## Pass counts per group", "",
         "| group | " + " | ".join(data) + " |", "|---|" + "---|" * len(data)]
    for g in groups + ["total"]:
        cells = []
        for rs in data.values():
            sel = [r for r in rs if g == "total" or r["name"].startswith(g + "/")]
            cells.append(f"{sum(r['ok'] for r in sel)}/{len(sel)}")
        L.append(f"| {g} | " + " | ".join(cells) + " |")
    byerr = collections.defaultdict(list)
    for r in data[base]:
        fe = first_error(r)
        if fe:
            byerr[fe[:3]].append((r["name"], fe[3]))
    L += ["", f"## Failures of `{base}` grouped by first error", "",
          "| count | stage | code | first error | owner | example |", "|---|---|---|---|---|---|"]
    for (stage, code, msg), ex in sorted(byerr.items(), key=lambda kv: -len(kv[1])):
        n, at = ex[0]
        L.append(f"| {len(ex)} | {stage} | {code} | {msg.replace('|', '/')} | {owner(stage, code, msg)} | `{n}` {('(' + at + ')') if at else ''} |")
    L += ["", "## Tests per failure group", ""]
    for (stage, code, msg), ex in sorted(byerr.items(), key=lambda kv: -len(kv[1])):
        L.append(f"- {stage} {code} {msg}: " + ", ".join(n for n, _ in ex))
    open(out, "w").write("\n".join(L) + "\n")


main()
