"""Generate lib/NATIVE.md from the vendored std sources.

usage: python3 -I tools/gen_native_md.py > lib/NATIVE.md   (run from the repo root)

Every subprogram declared in std.textio, std.env, std.reflection (protected
methods) and std.standard (NOW) has no VHDL body in the IEEE sources, so yavs
supplies it natively. The implicit (predefined) operations are listed as
families in the static part below.
"""
import re

LIB = "lib/std"


def read(rev, name):
    with open(f"{LIB}/{rev}/{name}.vhdl", encoding="latin-1") as f:
        return f.read()


def strip(s):
    s = re.sub(r"--[^\n]*", "", s)
    return re.sub(r"\s+", " ", s)


def split_top(s, sep):
    out, depth, cur = [], 0, ""
    for ch in s:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == sep and depth == 0:
            out.append(cur)
            cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur)
    return out


DECL = re.compile(
    r"^(?:(?:impure|pure) )?(procedure|function) (\"[^\"]+\"|\w+)\s*(?:\((.*)\))?\s*(?:return ([\w.']+))?$",
    re.I,
)


def subprograms(src):
    """Yield (kind, name, params[(names, class, mode, type)], ret, impure) for each declaration."""
    for stmt in split_top(strip(src), ";"):
        # The first declaration of a package shares its statement with `package X is`.
        stmt = re.sub(r"^.*\bpackage \w+ is ", "", stmt.strip(), flags=re.I)
        m = DECL.match(stmt)
        if not m:
            continue
        kind, name, plist, ret = m.group(1), m.group(2), m.group(3), m.group(4)
        params = []
        for p in split_top(plist or "", ";"):
            p = p.strip()
            mm = re.match(r"(?:(file|signal|variable|constant)\s+)?([\w, ]+?)\s*:\s*(?:(in|out|inout)\s+)?([\w.']+)", p, re.I)
            assert mm, (name, p)
            cls = (mm.group(1) or "").lower()
            mode = (mm.group(3) or "in").lower()
            params.append(([n.strip() for n in mm.group(2).split(",")], cls, mode, mm.group(4).lower()))
        yield kind.lower(), name.strip('"').lower() if name.startswith('"') else name.lower(), params, (ret or "").lower(), "impure" in stmt.lower().split(kind.lower())[0]


def sig(params):
    parts = []
    for names, cls, mode, ty in params:
        for _ in names:
            parts.append(ty)
    return "_".join(parts) if parts else "void"


def text(params):
    out = []
    for names, cls, mode, ty in params:
        pre = (cls + " ") if cls else ""
        out.append(f"{pre}{', '.join(names)}: {mode if mode != 'in' or cls == '' else ''} {ty}".replace(":  ", ": ").replace(": in ", ": in "))
    return "; ".join(out)


def package_items(rev, pkg):
    return list(subprograms(read(rev, pkg)))


def protected_items(rev):
    """reflection: yield (protected type name, subprogram)."""
    src = strip(read(rev, "reflection"))
    for m in re.finditer(r"type (\w+) is protected (.*?) end protected", src, re.I):
        for it in subprograms(m.group(2)):
            yield m.group(1).lower(), it


rows = []  # (pkg, owner, name, signature text, ret, symbol, revs)
table = {}


def add(pkg, owner, it, rev):
    kind, name, params, ret, _ = it
    s = sig(params)
    sym = f"yavs.{pkg}." + (f"{owner}." if owner else "") + re.sub(r"\W", "_", name if name[0].isalpha() else {"+": "add", "-": "sub", "/": "div", "*": "mul"}.get(name, name)) + "." + s
    sym = sym.replace("'", "_")
    # ret is part of identity for functions overloaded on result (getenv)
    if kind == "function" and ret:
        sym += ".r_" + ret.replace("'", "_")
    key = (pkg, owner, kind, name, text(params), ret)
    table.setdefault(key, {"sym": sym, "revs": set()})["revs"].add(rev)


for rev in ("2008", "2019"):
    for it in package_items(rev, "textio"):
        add("textio", "", it, rev)
    for it in package_items(rev, "env"):
        add("env", "", it, rev)
    # standard: only NOW is declared with a visible name and no body
    for it in package_items(rev, "standard"):
        add("standard", "", it, rev)
for owner, it in protected_items("2019"):
    add("reflection", owner, it, "2019")


def revs(r):
    return "2008, 2019" if r == {"2008", "2019"} else next(iter(r))


print("""# Native subprograms of the std library

Generated by `tools/gen_native_md.py` from `lib/std/{2008,2019}`. Do not edit by hand.

The IEEE sources for `standard`, `textio`, `env` and `reflection` contain **no package
bodies**, so every subprogram below is implemented natively by yavs (crate `yavs-std`).
The ieee packages are ordinary VHDL with bodies and need no natives; a few hot subprograms
also run natively (`yavs-ir` `ieee`, `YAVS_NO_NATIVE_IEEE`), keyed by mangled name, not listed here.

## Symbol naming

`yavs.<package>.[<protected type>.]<name>.<param types joined by _>[.r_<return type>]`

- Lower case. `void` stands for an empty parameter list. Parameter modes and classes are not part
  of the symbol (they are in the Signature column); the parameter types are the declared type
  marks, so `VALUE: out BIT_VECTOR` gives `bit_vector`.
- Operators use `add sub mul div` for `+ - * /`; the return type suffix `.r_<type>` is added for
  functions only, so overloads that differ only in the result type (`getenv`) stay distinct.
- A protected-type method additionally takes the object (`self`) as first argument; the protected
  type name is the `<protected type>` component, in lower case, e.g.
  `yavs.reflection.subtype_mirror_pt.get_type_class.void.r_type_class`.
- Default values (`:= X`) are omitted from the Signature column; see the source.
- The symbol is stable: it depends only on the declaration text in the vendored IEEE source.

## 1. Explicitly declared, no body (""" + str(len(table)) + """ rows)

Revision is the standard revision whose vendored source declares the subprogram.
`std.standard` appears with one row (`now`); the rest is in `textio`, `env` and `reflection`.
The textio `alias` declarations (BREAD, HEX_READ, STRING_WRITE, ...) are not natives: they
name the subprograms in this table. The `std_logic_textio` package is aliases only.
""")
by_pkg = {}
for key, v in table.items():
    by_pkg.setdefault(key[0], []).append((key, v))
total = 0
for pkg in ("standard", "textio", "env", "reflection"):
    items = by_pkg.get(pkg, [])
    total += len(items)
    print(f"### std.{pkg} ({len(items)})\n")
    print("| Native symbol | Signature | Revision |")
    print("|---|---|---|")
    for (p, owner, kind, name, params, ret), v in items:
        impure = ""
        s = f"{kind} {owner + '.' if owner else ''}{name}" + (f" ({params})" if params else "") + (f" return {ret}" if ret else "")
        print(f"| `{v['sym']}` | `{s}` | {revs(v['revs'])} |")
    print()

